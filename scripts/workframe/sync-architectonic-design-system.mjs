import { createHash } from 'node:crypto'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(scriptDir, '..', '..')
const sourceRoot = resolve(
  process.env.ARCHITECTONIC_DESIGN_SYSTEM_DIR || join(repoRoot, '..', 'architectonic', 'design-system'),
)
const outputRoot = join(repoRoot, 'apps', 'web', 'src', 'styles', 'architectonic', 'generated')
const registryOutput = join(repoRoot, 'apps', 'web', 'src', 'generated', 'architectonicThemes.ts')
const indexOutput = join(repoRoot, 'apps', 'web', 'index.html')

const required = [
  'package.json',
  'globals.css',
  join('modules', 'styles.module.css'),
  join('modules', 'toggle.module.css'),
  join('themes', 'manifest.json'),
  join('themes', 'mono.css'),
]

const missingSourceFiles = required.filter((relativePath) => !existsSync(join(sourceRoot, relativePath)))
if (missingSourceFiles.length) {
  const vendoredManifest = join(outputRoot, 'manifest.json')
  if (!process.env.ARCHITECTONIC_DESIGN_SYSTEM_DIR && existsSync(vendoredManifest) && existsSync(registryOutput)) {
    const vendored = JSON.parse(readFileSync(vendoredManifest, 'utf8'))
    console.log(`Using vendored ${vendored.package} ${vendored.version} (${vendored.themes.length} themes)`)
    process.exit(0)
  }
  throw new Error(`Architectonic design-system source is incomplete: ${missingSourceFiles.join(', ')}`)
}

const manifest = JSON.parse(readFileSync(join(sourceRoot, 'themes', 'manifest.json'), 'utf8'))
const packageMeta = JSON.parse(readFileSync(join(sourceRoot, 'package.json'), 'utf8'))
const ids = manifest.themes.map((theme) => theme.id)
if (!ids.includes(manifest.defaultTheme) || new Set(ids).size !== ids.length) {
  throw new Error('Architectonic theme manifest has an invalid default or duplicate ids')
}

rmSync(outputRoot, { recursive: true, force: true })
mkdirSync(join(outputRoot, 'themes'), { recursive: true })
mkdirSync(join(outputRoot, 'components'), { recursive: true })
mkdirSync(dirname(registryOutput), { recursive: true })

copyFileSync(join(sourceRoot, 'globals.css'), join(outputRoot, 'globals.css'))
copyFileSync(join(sourceRoot, 'modules', 'styles.module.css'), join(outputRoot, 'relief.css'))
copyFileSync(join(sourceRoot, 'modules', 'toggle.module.css'), join(outputRoot, 'components', 'toggle.css'))

const themeFiles = readdirSync(join(sourceRoot, 'themes'))
  .filter((name) => name.endsWith('.css'))
  .sort((a, b) => a.localeCompare(b))

for (const name of themeFiles) {
  copyFileSync(join(sourceRoot, 'themes', name), join(outputRoot, 'themes', name))
}

const importedThemeFiles = ['mono.css', ...themeFiles.filter((name) => name !== 'mono.css')]
const imports = [
  '/* Generated by scripts/workframe/sync-architectonic-design-system.mjs. */',
  "@import './globals.css';",
  "@import './themes/mono.css';",
  "@import './relief.css';",
  "@import './components/toggle.css';",
  ...importedThemeFiles.slice(1).map((name) => `@import './themes/${name}';`),
  '',
].join('\n')
writeFileSync(join(outputRoot, 'imports.css'), imports)

const sourceHash = createHash('sha256')
for (const path of [
  'globals.css',
  'modules/styles.module.css',
  'modules/toggle.module.css',
  'themes/manifest.json',
  ...themeFiles.map((name) => `themes/${name}`),
]) {
  sourceHash.update(path)
  sourceHash.update(readFileSync(join(sourceRoot, path)))
}

const snapshot = {
  package: packageMeta.name,
  version: packageMeta.version,
  sourceHash: sourceHash.digest('hex'),
  ...manifest,
}
writeFileSync(join(outputRoot, 'manifest.json'), `${JSON.stringify(snapshot, null, 2)}\n`)

const registrySource = `/* Generated by scripts/workframe/sync-architectonic-design-system.mjs. */
export const ARCHITECTONIC_THEME_REGISTRY = ${JSON.stringify(snapshot, null, 2)} as const

export type ArchitectonicTheme = (typeof ARCHITECTONIC_THEME_REGISTRY.themes)[number]['id']
export type ArchitectonicThemeDefinition = (typeof ARCHITECTONIC_THEME_REGISTRY.themes)[number]
`
writeFileSync(registryOutput, registrySource)

const bootstrapSource = `/* Generated by scripts/workframe/sync-architectonic-design-system.mjs. */
;(() => {
  try {
    const definitions = ${JSON.stringify(Object.fromEntries(manifest.themes.map((theme) => [theme.id, theme])))}
    const aliases = ${JSON.stringify({ ...manifest.legacyAliases, 'strato-dark': 'liquid-glass-dark', 'neo-blue': 'neo-dark' })}
    const stored = localStorage.getItem('wf-theme')
    const theme = definitions[stored] ? stored : aliases[stored] || ${JSON.stringify(manifest.defaultTheme)}
    const definition = definitions[theme]
    if (theme !== stored) localStorage.setItem('wf-theme', theme)
    const root = document.documentElement
    root.dataset.theme = theme
    root.dataset.archTheme = theme
    root.dataset.colorMode = definition.mode
    root.dataset.style = definition.style
    root.dataset.texture = definition.texture
    root.dataset.chromeMode = definition.style === 'shadows' ? 'relief' : definition.style === 'glass' ? 'glass' : 'line'
    root.dataset.density = 'technical'
    root.dataset.space = 'default'
    root.dataset.typeScale = 'compact'
    root.style.colorScheme = definition.mode
  } catch (_) {}
})()
`
const bootstrapStart = '    <!-- architectonic-theme-bootstrap:start -->'
const bootstrapEnd = '    <!-- architectonic-theme-bootstrap:end -->'
const indexSource = readFileSync(indexOutput, 'utf8')
const startIndex = indexSource.indexOf(bootstrapStart)
const endIndex = indexSource.indexOf(bootstrapEnd)
if (startIndex < 0 || endIndex < startIndex) {
  throw new Error('Workframe index.html is missing Architectonic theme bootstrap markers')
}
const bootstrapBlock = `${bootstrapStart}\n    <script>\n${bootstrapSource
  .split('\n')
  .map((line) => `      ${line}`)
  .join('\n')}    </script>\n${bootstrapEnd}`
writeFileSync(
  indexOutput,
  `${indexSource.slice(0, startIndex)}${bootstrapBlock}${indexSource.slice(endIndex + bootstrapEnd.length)}`,
)

console.log(
  `Synced ${manifest.themes.length} Architectonic themes (${packageMeta.version}, ${themeFiles.length} CSS files)`,
)
